// Build step for the tutorial PREVIEW iframe (public/tutorial/host.html).
//
// tut-host.html, tut-sw.js and tut-<slug>.js scenarios are committed source at
// apps/sui-site/public/ root (the deck build copies only TOP-LEVEL public/
// files, so the preview assets are flat with a `tut-` prefix rather than under
// a public/tutorial/ subdir). The only DERIVED asset is the preview theme: the
// exact three sheets the top
// document links (the @ship/tokens base = tokens.css + themes.css, then the
// SUI brand sui-theme.css, then base.css), concatenated so every `var(--…)`
// inside the sandboxed preview resolves identically to the page — without the
// preview reaching into the app's hashed `/assets/*.css` bundles.
//
// Run: `node scripts/gen-tutorial-host.mjs` (from apps/sui-site). Wired into the
// package.json `gen` script alongside gen-manifest + gen-tutorial.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO = resolve(__dirname, '../../..')
const SITE = resolve(__dirname, '..')

// Order = cascade: the @ship/tokens base palette + density/theme channels, then
// the SUI brand re-paint, then the document-level base styles.
const SHEETS = [
  ['@ship/tokens · tokens.css', join(REPO, 'packages/sui/tokens/src/tokens.css')],
  ['@ship/tokens · themes.css', join(REPO, 'packages/sui/tokens/src/themes.css')],
  ['sui-site · sui-theme.css', join(SITE, 'src/sui-theme.css')],
  ['sui-site · base.css', join(SITE, 'src/base.css')],
]

const parts = []
for (const [label, path] of SHEETS) {
  parts.push(`/* ============================================================\n   ${label}\n   ============================================================ */`)
  parts.push(readFileSync(path, 'utf8'))
}

const banner = `/* @generated by scripts/gen-tutorial-host.mjs — DO NOT EDIT.
   Concatenation of the SUI token + theme + base sheets for the tutorial
   preview iframe (public/tutorial/host.html). Regenerate via the gen step. */\n\n`

// The deck copies only TOP-LEVEL public/ files (not subdirs), so every tutorial
// preview asset lives at public/ root with a `tut-` prefix.
const OUT_DIR = join(SITE, 'public')
mkdirSync(OUT_DIR, { recursive: true })
const OUT = join(OUT_DIR, 'tut-preview-theme.css')
writeFileSync(OUT, banner + parts.join('\n\n') + '\n')
console.log(`wrote ${OUT} — ${SHEETS.length} sheets concatenated`)

// Regenerate public/tut-preview-theme.css — the framework token/theme/contract
// sheets concatenated so the tutorial preview iframe (public/tut-host.html) resolves
// every var(--…) and element skin identically to the top document. The original
// gen-tutorial-host generator was removed with the <navbar> refactor (ba48c1f),
// leaving tut-host.html's <link href="/tut-preview-theme.css"> dangling (404 →
// unstyled preview). This restores it minimally.
//
// Framework `@font-face` rules in contracts.css use relative
// `url('./fonts/<file>')` so the deck bundler can emit hashed woff2 assets.
// This sheet is served as a static public asset (not bundled), so those
// relatives would resolve to `/fonts/<file>` and 404. Rewrite them to the
// framework font route (`GET /_deck/fonts/{file}`) which serves the token-
// package SSOT — never copy woff2 into `public/fonts`.
//
//   node apps/sail-site/scripts/gen-tut-preview-theme.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Stable deck route for framework woff2 (see deck-core `serve_framework_font`). */
export const FRAMEWORK_FONT_ROUTE = '/_deck/fonts'

/**
 * Rewrite relative framework font URLs to the deck font route.
 * Handles `url('./fonts/X')`, `url("./fonts/X")`, and `url(./fonts/X)`.
 */
export function rewriteFrameworkFontUrls(css) {
  return css.replace(
    /url\(\s*(['"]?)\.\/fonts\/([^'")\s]+)\1\s*\)/g,
    (_m, _q, file) => `url('${FRAMEWORK_FONT_ROUTE}/${file}')`,
  )
}

/** Concatenate framework sheets and rewrite font URLs for public serving. */
export function buildTutPreviewThemeCss(tokensSrc) {
  const sheets = ['tokens.css', 'themes.css', 'contracts.css', 'element-skins.css']
  const body = rewriteFrameworkFontUrls(
    sheets
      .map((f) => `/* ─── ${f} ─── */\n${readFileSync(resolve(tokensSrc, f), 'utf8')}`)
      .join('\n\n'),
  )

  // Guard: never emit the relative form that 404s under /public.
  if (
    body.includes("url('./fonts/") ||
    body.includes('url("./fonts/') ||
    body.includes('url(./fonts/')
  ) {
    throw new Error(
      "gen-tut-preview-theme: residual relative url('./fonts/…') after rewrite — framework fonts would 404",
    )
  }
  if (!body.includes(`url('${FRAMEWORK_FONT_ROUTE}/`)) {
    throw new Error(
      `gen-tut-preview-theme: expected rewritten framework font URLs under ${FRAMEWORK_FONT_ROUTE}/`,
    )
  }
  return { body, sheets }
}

const isMain =
  process.argv[1] &&
  fileURLToPath(import.meta.url) === resolve(process.argv[1])

if (isMain) {
  const here = dirname(fileURLToPath(import.meta.url))
  const tokensSrc = resolve(here, '../../../packages/sail/tokens/src')
  const { body, sheets } = buildTutPreviewThemeCss(tokensSrc)
  const dest = resolve(here, '../public/tut-preview-theme.css')
  writeFileSync(
    dest,
    `/* GENERATED by scripts/gen-tut-preview-theme.mjs — do not hand-edit. */\n${body}`,
  )
  console.log(`wrote ${dest} (${body.length} bytes from ${sheets.join(', ')})`)
}

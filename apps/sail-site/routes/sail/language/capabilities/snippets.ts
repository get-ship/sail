// Code snippets for the Capabilities page. Kept OUT of the controller so the
// compiler's scope scan isn't fooled by patterns inside these strings.
//
// The SAIL snippets here are compiled by
// crates/sail/compiler/tests/site_snippets_compile.rs, which compiles each one
// STANDALONE — with no host and therefore no granted capability. That is why a
// snippet reads its capability through the controller's `ctx` (ordinary
// TypeScript) rather than naming it bare in a template expression: a bare
// `{route.pathname()}` is exactly the compile error this page documents, and it
// would — correctly — fail the suite.
export const code = {
  // How this very page reads the capability deck grants it.
  read: `<controller>
import { controller, derived } from '@ship/sail-runtime'

export default controller((ctx) => {
  // \`route\` is not imported and not declared here. The host put it on the
  // scope; the generated Scope types it as RouteSignals.
  const here = derived(() => ctx.route.pathname())
  return { here }
})
</controller>

<p>You are reading {here()}.</p>`,

  // The generated .sail.d.ts an app with one declared client gets.
  scope: `// generated by sail-compiler — DO NOT EDIT
import type { Clients, RouteSignals } from '@ship/sail-runtime'

export interface Scope {
  clients: Clients
  api: Clients['api']
  navigate: (path: string) => void
  route: RouteSignals
}`,

  // What the manifest declares. One entry in, one typed member out.
  manifest: `{
  "clients": {
    "api": { "from": "./src/api", "import": "api" }
  }
}`,

  // The diagnostic, verbatim in shape: name, then what IS in scope.
  // The compiler sorts the available names before printing them.
  refusal: `Identifier 'session' is not declared in scope.
Available: api, clients, here, navigate, route.`,
}

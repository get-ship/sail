/**
 * Thread B — generated-and-tracked must name a generator.
 * routes/entry/components.gen.ts are gitignored (state a).
 * Remaining tracked *.gen.ts stay tracked + header-named (state b).
 * Full regen-diff of prop-registry waits on a type-gate step; this
 * gate is the inventory so a third state cannot land silently.
 */
import { describe, expect, test } from 'bun:test'
import { execSync } from 'node:child_process'
import { readFileSync } from 'node:fs'

const trackedGen = (): string[] =>
  execSync("git ls-files '*.gen.ts' '*.gen.tsx'", { encoding: 'utf8' })
    .trim()
    .split('\n')
    .filter(Boolean)

const KNOWN_GENERATORS = [
  'sail-compiler -- prop-registry',
  'cargo run -p sail-compiler -- prop-registry',
  'gen-runtime-surface.ts',
  'scripts/gen-runtime-surface.ts',
]

describe('tracked generated TS names its generator', () => {
  test('every tracked *.gen.ts is AUTO-GENERATED by a known command', () => {
    const files = trackedGen()
    expect(files.length, 'expected the three site surface gens').toBeGreaterThan(0)
    const bad: string[] = []
    for (const f of files) {
      const head = readFileSync(f, 'utf8').split('\n').slice(0, 4).join('\n')
      if (!head.includes('AUTO-GENERATED')) {
        bad.push(`${f}: missing AUTO-GENERATED header`)
        continue
      }
      if (!KNOWN_GENERATORS.some((g) => head.includes(g))) {
        bad.push(`${f}: header does not name a known generator`)
      }
    }
    expect(bad, bad.join('\n')).toEqual([])
  })
})

//! Generated consumer catalog for `@ship/sail-l1`.
//!
//! This is a TypeScript projection of the stdlib — tags, families, props,
//! axes, spent Style concerns. It is **not** the `.sail` definitions and
//! **not** a test package. Docs / Studio / probe import the package; they
//! do not copy `L1_CATALOG` or hand `contract.ts` files.
//!
//! Theme Studio concern overlay (border, fg, …) reads `concerns`. Persistence
//! of those overlays is parked — do not invent `component.*` tokens here.

use std::collections::BTreeSet;
#[cfg(not(target_arch = "wasm32"))]
use std::path::Path;

use crate::l1_manifest::{l1_entries, L1Entry};
use crate::stdlib::{self, families, family_of, family_tags, is_family_host};

/// Emit `catalog.ts` for `@ship/sail-l1`.
#[cfg(not(target_arch = "wasm32"))]
pub fn emit_catalog_ts(out: &Path) -> Result<(), String> {
    let body = catalog_ts();
    if let Some(parent) = out.parent() {
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    std::fs::write(out, body).map_err(|e| e.to_string())?;
    Ok(())
}

pub fn catalog_ts() -> String {
    let entries = l1_entries();
    let mut ts = String::new();
    ts.push_str("// AUTO-GENERATED by `cargo run -p sail-compiler -- l1-surface`. Do not edit.\n");
    ts.push_str("// Projection of crates/sail/compiler/stdlib — not the .sail sources,\n");
    ts.push_str("// not a test package. Consumers import @ship/sail-l1.\n\n");
    ts.push_str("export type L1Role = 'host' | 'part'\n\n");
    ts.push_str(
        "export type L1Prop = {\n  name: string\n  type: string\n  default?: string\n  values?: string[]\n}\n\n",
    );
    ts.push_str(
        "export type L1Axis = {\n  name: string\n  values: string[]\n  optional: boolean\n}\n\n",
    );
    ts.push_str(
        "export type L1Tag = {\n  tag: string\n  family: string\n  role: L1Role\n  description: string\n  acceptsChildren: boolean\n  props: L1Prop[]\n  axes: L1Axis[]\n  /** Style concerns this host's program spends. Overlay surface — not component.* tokens. */\n  concerns: string[]\n}\n\n",
    );
    ts.push_str("export type L1Family = {\n  id: string\n  host: string\n  parts: string[]\n}\n\n");

    ts.push_str("export const FAMILIES: readonly L1Family[] = [\n");
    for id in families() {
        let tags = family_tags(id);
        let parts: Vec<&str> = tags.iter().copied().filter(|t| *t != id).collect();
        ts.push_str("  { ");
        ts.push_str(&format!(
            "id: {id}, host: {id}, parts: [{parts}]",
            id = ts_str(id),
            parts = parts
                .iter()
                .map(|p| ts_str(p))
                .collect::<Vec<_>>()
                .join(", ")
        ));
        ts.push_str(" },\n");
    }
    ts.push_str("]\n\n");

    ts.push_str("export const TAGS: readonly L1Tag[] = [\n");
    for entry in &entries {
        ts.push_str(&tag_literal(entry));
    }
    ts.push_str("]\n\n");

    ts.push_str("export const TAG_BY_ID: Readonly<Record<string, L1Tag>> = Object.fromEntries(\n");
    ts.push_str("  TAGS.map((t) => [t.tag, t]),\n");
    ts.push_str(")\n");
    ts
}

fn tag_literal(entry: &L1Entry) -> String {
    let family = family_of(&entry.tag);
    let role = if is_family_host(&entry.tag) {
        "host"
    } else {
        "part"
    };
    let src = stdlib::sources()
        .iter()
        .find(|(t, _)| *t == entry.tag)
        .map(|(_, s)| *s)
        .unwrap_or("");
    let concerns = concerns_spent(src);

    let mut props = String::new();
    for p in &entry.attributes {
        props.push_str("      { ");
        props.push_str(&format!(
            "name: {}, type: {}",
            ts_str(&p.name),
            ts_str(&p.ty)
        ));
        if let Some(d) = &p.default {
            props.push_str(&format!(", default: {}", ts_str(d)));
        }
        if !p.values.is_empty() {
            props.push_str(&format!(
                ", values: [{}]",
                p.values
                    .iter()
                    .map(|v| ts_str(v))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        props.push_str(" },\n");
    }

    let mut axes = String::new();
    for a in &entry.matrix.axes {
        axes.push_str(&format!(
            "      {{ name: {}, values: [{}], optional: {} }},\n",
            ts_str(&a.name),
            a.values
                .iter()
                .map(|v| ts_str(v))
                .collect::<Vec<_>>()
                .join(", "),
            a.optional
        ));
    }

    format!(
        "  {{\n    tag: {tag},\n    family: {family},\n    role: '{role}',\n    description: {desc},\n    acceptsChildren: {kids},\n    props: [\n{props}    ],\n    axes: [\n{axes}    ],\n    concerns: [{concerns}],\n  }},\n",
        tag = ts_str(&entry.tag),
        family = ts_str(family),
        role = role,
        desc = ts_str(&entry.description),
        kids = if entry.accepts_children { "true" } else { "false" },
        props = props,
        axes = axes,
        concerns = concerns.iter().map(|c| ts_str(c)).collect::<Vec<_>>().join(", "),
    )
}

/// Style concerns the source program actually calls (`border(`, `fg(`).
/// This is the Theme Studio overlay surface — not `component.<tag>.*`.
pub fn concerns_spent(source: &str) -> Vec<String> {
    let mut hit = BTreeSet::new();
    for row in spinnaker::offered_rows() {
        if row.tag != spinnaker::VocabTag::Concern {
            continue;
        }
        let needle = format!("{}(", row.name);
        if source.contains(&needle) {
            hit.insert(row.name.to_string());
        }
    }
    hit.into_iter().collect()
}

fn ts_str(s: &str) -> String {
    let mut out = String::from("'");
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            _ => out.push(ch),
        }
    }
    out.push('\'');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn card_spends_surface_concerns() {
        let src = include_str!("../stdlib/card.sail");
        let c = concerns_spent(src);
        assert!(c.iter().any(|x| x == "border"), "{c:?}");
        assert!(c.iter().any(|x| x == "fg"), "{c:?}");
        assert!(c.iter().any(|x| x == "bg"), "{c:?}");
        assert!(
            !c.iter().any(|x| x.contains("component")),
            "must not invent component tokens: {c:?}"
        );
    }

    #[test]
    fn catalog_names_tabs_family() {
        let ts = catalog_ts();
        assert!(ts.contains("id: 'tabs'"));
        assert!(ts.contains("host: 'tabs'"));
        assert!(ts.contains("'tab-list'"));
        assert!(ts.contains("family: 'tabs'"));
        assert!(ts.contains("role: 'part'"));
    }
}

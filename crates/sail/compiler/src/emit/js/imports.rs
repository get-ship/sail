use super::super::writer::{Writer, js_string};
use crate::CompileOpts;
use crate::action_manifest;
use crate::lower::Lowered;

/// Specifier for every auto-imported `use:` action. The ABI path
/// (`@ship/sail-runtime/internal`) re-exports the runtime front door,
/// which only carries the *public* action surface — internal stamps
/// (stdlib-only) live exclusively on this subpath so they resolve
/// without polluting the author API.
const ACTIONS_SPECIFIER: &str = "@ship/sail-runtime/actions";

pub(super) fn emit_imports(
    w: &mut Writer,
    lowered: &Lowered,
    opts: &CompileOpts,
    uses_templates: bool,
    uses_delegation: bool,
) {
    let mut imports: Vec<String> = lowered
        .runtime_imports
        .iter()
        .map(|s| s.to_string())
        .collect();
    for &name in &lowered.motion_builtins {
        let s = name.to_string();
        if !imports.contains(&s) {
            imports.push(s);
        }
    }
    // The template cloner is emitted whenever a static subtree is hoisted.
    if uses_templates && !imports.iter().any(|i| i == "__tpl") {
        imports.push("__tpl".to_string());
    }
    if uses_delegation && !imports.iter().any(|i| i == "delegateEvents") {
        imports.push("delegateEvents".to_string());
    }

    // Split `use:` action symbols onto `@ship/sail-runtime/actions` so
    // internal stamps (not re-exported from the front door / ABI barrel)
    // still resolve. Everything else stays on the compiler ABI path.
    let (action_imports, mut abi_imports): (Vec<String>, Vec<String>) =
        imports.into_iter().partition(|name| is_action_symbol(name));
    abi_imports.sort();
    let mut action_imports = action_imports;
    action_imports.sort();

    w.line("// AUTO-GENERATED by sail-compiler. Do not edit.");
    if abi_imports.is_empty() {
        w.line("import \"@ship/sail-runtime/internal\";");
    } else {
        w.line(&format!(
            "import {{ {} }} from \"@ship/sail-runtime/internal\";",
            abi_imports.join(", ")
        ));
    }
    if !action_imports.is_empty() {
        w.line(&format!(
            "import {{ {} }} from \"{ACTIONS_SPECIFIER}\";",
            action_imports.join(", ")
        ));
    }
    if !lowered.dom_imports.is_empty() {
        let dom: Vec<String> = lowered.dom_imports.iter().map(|s| s.to_string()).collect();
        w.line(&format!(
            "import {{ {} }} from \"@ship/sail-dom\";",
            dom.join(", ")
        ));
    }
    if lowered.uses_template_hooks {
        w.line("import \"@ship/sail-runtime/template-hooks\";");
    }
    if let Some(setup) = &opts.setup_url {
        w.line(&format!("import setup from {};", js_string(setup)));
    }
    // Per-used-tag component registration imports — the per-route resolver: the
    // bundler maps `@sail-tag/<tag>` to the component source and tree-shakes it
    // into the bundle (replacing the umbrella/islands registry). Off by
    // default; only the bundled path opts in via `emit_component_imports`.
    if opts.emit_component_imports {
        for tag in &lowered.used_component_tags {
            w.line(&format!(
                "import {};",
                js_string(&format!("@sail-tag/{tag}"))
            ));
        }
    }
    w.nl();
}

fn is_action_symbol(name: &str) -> bool {
    action_manifest::ACTIONS.iter().any(|a| a.name == name)
}

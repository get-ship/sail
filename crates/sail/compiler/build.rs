//! Build script — emits `BUILD_*` env vars and bakes the DTCG token model
//! (`packages/sail/tokens/model/**`) into the compiler so theme generate /
//! catalog ids work without a monorepo checkout on disk.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    build_info::emit_build_env();
    bake_tokens_model();
}

fn bake_tokens_model() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    // crates/sail/compiler → repo root → packages/sail/tokens/model
    let model_src = manifest
        .join("../../..")
        .join("packages/sail/tokens/model");
    let model_src = model_src
        .canonicalize()
        .unwrap_or_else(|_| model_src.clone());

    println!("cargo:rerun-if-changed={}", model_src.display());
    walk_rerun(&model_src);

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let dest = out_dir.join("baked_tokens_model.rs");

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    collect_model_files(&model_src, &model_src, &mut files);
    files.sort_by(|a, b| a.0.cmp(&b.0));

    if files.is_empty() {
        panic!(
            "tokens model bake: no files under {} — expected packages/sail/tokens/model/**",
            model_src.display()
        );
    }

    let mut body = String::from(
        "/// Compile-time baked DTCG catalog (relative path → file body).\n\
         /// Generated by crates/sail/compiler/build.rs — do not edit.\n\
         pub static BAKED_MODEL_FILES: &[(&str, &str)] = &[\n",
    );
    for (rel, abs) in &files {
        // Escape for include_str! path: use absolute path string with forward slashes.
        let abs_s = abs.display().to_string().replace('\\', "/");
        body.push_str(&format!(
            "    ({rel:?}, include_str!(r\"{abs_s}\")),\n"
        ));
    }
    body.push_str("];\n");

    fs::write(&dest, body).unwrap_or_else(|e| {
        panic!("write {}: {e}", dest.display());
    });
}

fn walk_rerun(dir: &Path) {
    let Ok(rd) = fs::read_dir(dir) else {
        return;
    };
    for ent in rd.flatten() {
        let p = ent.path();
        println!("cargo:rerun-if-changed={}", p.display());
        if p.is_dir() {
            walk_rerun(&p);
        }
    }
}

fn collect_model_files(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(rd) = fs::read_dir(dir) else {
        return;
    };
    for ent in rd.flatten() {
        let p = ent.path();
        if p.is_dir() {
            collect_model_files(root, &p, out);
            continue;
        }
        if !p.is_file() {
            continue;
        }
        let Some(name) = p.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        // Bake DTCG JSON + companion chrome CSS consumed by generate.
        let ok = name.ends_with(".json")
            || name == "chrome.css"
            || name == "themes-chrome.css";
        if !ok {
            continue;
        }
        let rel = p
            .strip_prefix(root)
            .unwrap_or(&p)
            .to_string_lossy()
            .replace('\\', "/");
        out.push((rel, p));
    }
}

//! Build script — emits `BUILD_*` env vars and bakes the DTCG token model
//! (`packages/sail/tokens/model/**`) into the compiler so theme generate /
//! catalog ids work without a monorepo checkout on disk.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

#[path = "src/ts_native/fetch.rs"]
mod fetch;
#[path = "src/ts_native/pins.rs"]
mod pins;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/ts_native/pins.toml");
    println!("cargo:rerun-if-env-changed=SAIL_TS_NATIVE_TARBALL");
    println!("cargo:rerun-if-env-changed=SAIL_TS_NATIVE_OFFLINE");
    println!("cargo:rerun-if-env-changed=SAIL_TS_NATIVE_REQUIRED");
    build_info::emit_build_env();
    bake_tokens_model();
    extract_ts_native_sidecar();
}

fn extract_ts_native_sidecar() {
    let arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    if arch == "wasm32" {
        return;
    }
    let os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let (npm_os, npm_arch) = fetch::cargo_cfg_to_npm(&os, &arch);
    if pins::pin_for(&npm_os, &npm_arch).is_none() {
        return;
    }
    let profile = env::var("PROFILE").unwrap_or_else(|_| "debug".into());
    let dest = sidecar_dest(&profile);
    let offline = env::var_os("SAIL_TS_NATIVE_OFFLINE").is_some();
    let tarball_override = env::var_os("SAIL_TS_NATIVE_TARBALL").map(PathBuf::from);
    let required = env::var("SAIL_TS_NATIVE_REQUIRED")
        .map(|v| v == "1" || v.eq_ignore_ascii_case("true"))
        .unwrap_or(false)
        || profile == "release";
    let opts = fetch::EnsureOpts {
        dest,
        offline,
        tarball_override,
    };
    match fetch::ensure_sidecar(&npm_os, &npm_arch, &opts) {
        Ok(_) => {}
        Err(e) if required => {
            panic!(
                "sail-ts-native required (release / SAIL_TS_NATIVE_REQUIRED): {e}\n\
                 Place a verified tarball at $SAIL_TS_NATIVE_TARBALL or \
                 $CARGO_HOME/sail-ts-native/{}/, or run online once.",
                pins::TS_NATIVE_VERSION
            );
        }
        Err(e) => {
            println!("cargo:warning=sail-ts-native extract skipped: {e}");
        }
    }
}

fn sidecar_dest(profile: &str) -> PathBuf {
    if let Ok(target) = env::var("CARGO_TARGET_DIR") {
        if !target.is_empty() {
            return PathBuf::from(target).join(profile).join("sail-ts-native");
        }
    }
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let profile_dir = fetch::profile_dir_from_out_dir(&out_dir, profile).unwrap_or_else(|| {
        out_dir
            .ancestors()
            .nth(3)
            .map(Path::to_path_buf)
            .unwrap_or(out_dir)
    });
    profile_dir.join("sail-ts-native")
}

fn bake_tokens_model() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    // crates/sail/compiler → repo root → packages/sail/tokens/model
    let model_src = manifest.join("../../..").join("packages/sail/tokens/model");
    let model_src = model_src
        .canonicalize()
        .unwrap_or_else(|_| model_src.clone());

    println!("cargo:rerun-if-changed={}", model_src.display());
    walk_rerun(&model_src);

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let dest = out_dir.join("baked_tokens_model.rs");

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    collect_model_files(&model_src, &model_src, &mut files);
    files.sort_by(|a, b| a.0.cmp(&b.0));

    if files.is_empty() {
        panic!(
            "tokens model bake: no files under {} — expected packages/sail/tokens/model/**",
            model_src.display()
        );
    }

    let mut body = String::from(
        "/// Compile-time baked DTCG catalog (relative path → file body).\n\
         /// Generated by crates/sail/compiler/build.rs — do not edit.\n\
         pub static BAKED_MODEL_FILES: &[(&str, &str)] = &[\n",
    );
    for (rel, abs) in &files {
        // Escape for include_str! path: use absolute path string with forward slashes.
        let abs_s = abs.display().to_string().replace('\\', "/");
        body.push_str(&format!("    ({rel:?}, include_str!(r\"{abs_s}\")),\n"));
    }
    body.push_str("];\n");

    fs::write(&dest, body).unwrap_or_else(|e| {
        panic!("write {}: {e}", dest.display());
    });
}

fn walk_rerun(dir: &Path) {
    let Ok(rd) = fs::read_dir(dir) else {
        return;
    };
    for ent in rd.flatten() {
        let p = ent.path();
        println!("cargo:rerun-if-changed={}", p.display());
        if p.is_dir() {
            walk_rerun(&p);
        }
    }
}

fn collect_model_files(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(rd) = fs::read_dir(dir) else {
        return;
    };
    for ent in rd.flatten() {
        let p = ent.path();
        if p.is_dir() {
            collect_model_files(root, &p, out);
            continue;
        }
        if !p.is_file() {
            continue;
        }
        let Some(name) = p.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        // Bake DTCG JSON + companion chrome CSS consumed by generate.
        let ok = name.ends_with(".json") || name == "chrome.css" || name == "themes-chrome.css";
        if !ok {
            continue;
        }
        let rel = p
            .strip_prefix(root)
            .unwrap_or(&p)
            .to_string_lossy()
            .replace('\\', "/");
        out.push((rel, p));
    }
}

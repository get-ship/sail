//! Fuse the synthetic controller + client render into ONE self-contained ESM.
//!
//! The split two-file form (controller exporting `scope` + render importing it)
//! is what the SSR pipeline and the type-checked harness use. A consumer that
//! loads a `.sui` as a SINGLE module — the deck-bundler `load` hook, which
//! returns one module's code per id — needs the two halves merged. The merge
//! drops the cross-module `import { scope }` (the controller's `scope` const is
//! then in lexical scope), unions the two import blocks (multiple `import {…}
//! from "X"` lines are legal, but unioning them means a future name overlap
//! can't become a duplicate-binding SyntaxError), and concatenates
//! controller-body then client-body.

use std::collections::BTreeMap;

use super::super::writer::Writer;
use super::{emit_controller, render, AppManifest, AuthoredController};
use crate::diagnostics::CompileError;
use crate::ir::Program;
use crate::CompileMode;

/// The `import { scope }` specifier the client render carries to reach the
/// controller — dropped on merge (the controller's `scope` is now local).
const MERGED_CONTROLLER_SPEC: &str = "./__synthetic_controller__";

const MERGED_HEADER: &str = "\
// AUTO-GENERATED by sui-compiler `synthesize` — the MERGED CLIENT module: the
// synthetic controller (typed `scope`) and the client render (`default.setup`
// → `__mount` + `hydrate`) fused into one ESM. Do NOT edit. This is the
// single-module form the bundler `load` hook returns.";

/// Emit ONE self-contained CLIENT module. The result imports only the framework
/// singletons (`@ship/sui-runtime`, `@ship/sui-dom`), the manifest clients'
/// modules, and the authored controller — exactly what a browser/jsdom bundle
/// resolves.
pub fn emit_synthetic_client_module(
    program: &Program,
    manifest: &AppManifest,
    authored: Option<&AuthoredController>,
    mode: CompileMode,
    component_tag: Option<&str>,
) -> Result<String, CompileError> {
    // Per-view resolver, including the convention-backed `route`/`navigate`
    // names — the bundler and the SSR build both feed through this seam.
    let used = super::used_clients(program, manifest);
    let controller_ts = emit_controller(program, manifest, &used, authored, mode)?;
    let client_ts = render::emit_render_client(
        program,
        MERGED_CONTROLLER_SPEC,
        mode,
        component_tag,
    )?;
    let (ctrl_imports, ctrl_body) = split_module(&controller_ts);
    let (client_imports, client_body) = split_module(&client_ts);
    let merged_imports = merge_imports(&ctrl_imports, &client_imports, MERGED_CONTROLLER_SPEC);

    let mut w = Writer::new();
    w.line(MERGED_HEADER);
    for line in &merged_imports {
        w.line(line);
    }
    w.nl();
    w.push_str(&ctrl_body);
    w.nl();
    w.push_str(&client_body);
    Ok(w.into_string())
}

/// Split a generated synthetic module into its (import lines, body) halves.
/// The generated shape is: a leading `//` comment header, then a contiguous
/// run of `import …;` lines, a blank line, then the body. Header is dropped
/// (the merge emits its own); blank separators inside the import run are
/// skipped; everything from the first non-import, non-blank line on is body.
fn split_module(src: &str) -> (Vec<String>, String) {
    let mut imports: Vec<String> = Vec::new();
    let mut body = String::new();
    let mut in_body = false;
    for line in src.lines() {
        if in_body {
            body.push_str(line);
            body.push('\n');
            continue;
        }
        let t = line.trim_start();
        if t.starts_with("//") || t.is_empty() {
            continue; // header comment / blank separator
        }
        if t.starts_with("import ") {
            imports.push(line.to_string());
            continue;
        }
        // First real statement: body starts here.
        in_body = true;
        body.push_str(line);
        body.push('\n');
    }
    (imports, body)
}

/// Merge two import blocks into one, dropping the client's
/// `import { scope } from "<merged_spec>"` line and unioning value-named
/// imports (`import { a, b } from "X"`) and type-named imports
/// (`import type { … } from "X"`) per module so no binding is imported
/// twice. Non-named lines (default, namespace, side-effect) pass through,
/// deduplicated by exact text, in first-seen order.
fn merge_imports(a: &[String], b: &[String], drop_spec: &str) -> Vec<String> {
    // (is_type, spec) → ordered set of names.
    let mut named: BTreeMap<(bool, String), Vec<String>> = BTreeMap::new();
    let mut passthrough: Vec<String> = Vec::new();
    let drop_line = format!("import {{ scope }} from \"{drop_spec}\";");
    for line in a.iter().chain(b.iter()) {
        let l = line.trim();
        if l == drop_line {
            continue;
        }
        if let Some((is_type, spec, names)) = parse_named_import(l) {
            let entry = named.entry((is_type, spec)).or_default();
            for n in names {
                if !entry.contains(&n) {
                    entry.push(n);
                }
            }
        } else if !passthrough.contains(line) {
            passthrough.push(line.clone());
        }
    }
    let mut out = passthrough;
    for ((is_type, spec), mut names) in named {
        names.sort();
        let kw = if is_type { "import type" } else { "import" };
        out.push(format!("{kw} {{ {} }} from \"{spec}\";", names.join(", ")));
    }
    out
}

/// Parse `import { a, b as c } from "spec";` (or `import type { … }`) into
/// `(is_type, spec, names)`. Returns `None` for any other import shape, which
/// the caller passes through verbatim. Names keep their `as` aliasing intact.
fn parse_named_import(line: &str) -> Option<(bool, String, Vec<String>)> {
    let (is_type, rest) = match line.strip_prefix("import type ") {
        Some(r) => (true, r),
        None => (false, line.strip_prefix("import ")?),
    };
    let rest = rest.trim_start();
    let inner = rest.strip_prefix('{')?;
    let (names_part, after) = inner.split_once('}')?;
    let after = after.trim_start();
    let spec = after.strip_prefix("from ")?.trim().trim_end_matches(';').trim();
    let spec = spec.strip_prefix('"').and_then(|s| s.strip_suffix('"'))?;
    let names: Vec<String> = names_part
        .split(',')
        .map(|n| n.trim().to_string())
        .filter(|n| !n.is_empty())
        .collect();
    Some((is_type, spec.to_string(), names))
}

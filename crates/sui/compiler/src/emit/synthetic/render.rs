//! The **render** half of a synthetic view: the markup → DOM module.
//!
//! It imports the synthetic controller's typed `scope` and wires bindings
//! against it. Author expressions are rewritten with a `scope.` prefix so
//! `{route.params.id()}` compiles to `scope.route.params.id()` — resolved
//! against the controller's REAL, typed `scope` export, not the untyped
//! `$scope` proxy. That typing is what lets tsgo catch `scope.route.parms`
//! against `RouteSignals`.
//!
//! Unlike the desugar spike — which hand-rolled a minimal element/text
//! emitter — this REUSES the production [`TemplateEmitter`]. Driving the
//! same walk with a `"scope."` prefix is the whole point: every template
//! feature (`{#if/#for/#match/#while-*}`, `on:`, `bind:`, `class:`,
//! `style:`, slots, nested components) emits identically to production,
//! so the synthetic path inherits the emitter's full behavior for free.
//!
//! Two scope variables coexist in `mount()`:
//!   * `scope` — the typed import. Author expressions read `scope.X`, so
//!     tsgo checks them against the controller's `Scope` type.
//!   * `$scope` — the runtime-mutable scope (`Object.create(scope)`). The
//!     emitter's machinery (child scopes, per-row `__v` version signals,
//!     `bindWhileLoading({ signal: $scope.<data> })`) drives this. It
//!     inherits every member of `scope` through the prototype, so a
//!     machinery read of a `<data>` signal resolves to the same object an
//!     author read does — one source of truth, two reference paths.

use super::super::template_emit::TemplateEmitter;
use super::super::writer::{js_string, Writer};
use crate::bindings;
use crate::diagnostics::CompileError;
use crate::ir::*;
use crate::lower;

const HEADER: &str = "\
// AUTO-GENERATED by sui-compiler `synthesize` — the RENDER half (markup →
// DOM). Do NOT edit. Bindings resolve against the synthetic controller's
// typed `scope` export, so member typos are tsgo/tsc type errors.";

const CLIENT_HEADER: &str = "\
// AUTO-GENERATED by sui-compiler `synthesize` — the CLIENT half. Do NOT edit.
// `default.setup(ctx)` returns the `__mount` (CSR build) + `hydrate` (adopt
// SSR markers) the runtime `mount()` (packages/sui/runtime/src/mount.ts)
// expects. It reuses the SAME hydrate buffers the production view emit drives,
// so every template feature wires identically — the only difference from the
// SSR render is the contract shape (a setup-returned object, not a bare
// `mount`). Bindings resolve against the controller's typed `scope` export.";

const SCOPE_PREFIX: &str = "scope.";

/// Author-side runtime symbols that belong in the **controller**, not the
/// render. `lower` reports them in `runtime_imports`, but the render never
/// calls `component()`/`data()`/`live()`/`prop()` — those lower into the
/// controller's logic half. Everything else `lower` reports is a template
/// binder the mount body uses.
const CONTROLLER_ONLY_IMPORTS: &[&str] = &["component", "prop", "data", "live"];

/// The reusable template walk: drives the production [`TemplateEmitter`] with
/// the `scope.` author prefix and returns the emitted pieces. `is_view` gates
/// the hydrate-buffer population — `false` for the SSR mount-only render
/// (discarded), `true` for the client contract (which wires SSR markers).
/// `is_view` never alters the mount body or the boundary hoists; it only adds
/// the separate `hydrate_calls` buffer (and its `uses_*` flags), so the SSR
/// path stays byte-for-byte what it was before the client contract existed.
struct Walked {
    /// Mount body: the `createElement`/`appendChild`/`bind*` DOM build,
    /// parented at `container` and pushing disposers onto `__cleanups`.
    body: String,
    /// `const __wireBoundary_b<N>` + `{#while-*}` render-fn declarations the
    /// mount/hydrate bodies reference by name. Both capture `$scope`.
    hoists: String,
    /// `hydrate(root, ctx)` body statements (empty on the SSR walk).
    hydrate_calls: String,
    uses_text: bool,
    uses_markers: bool,
}

fn walk(program: &Program, is_view: bool) -> Walked {
    let registry = bindings::build(program);
    let mut emitter = TemplateEmitter::new(&registry, is_view).with_expr_prefix(SCOPE_PREFIX);

    let mut body_w = Writer::new();
    emitter.emit_top_level(&mut body_w, &program.template, "container", "__cleanups");

    let hoists = emitter.take_boundary_hoists();
    let uses_text = emitter.hydrate_uses_text();
    let uses_markers = emitter.hydrate_uses_markers();
    let hydrate_calls = emitter.take_hydrate_calls();
    Walked { body: body_w.into_string(), hoists, hydrate_calls, uses_text, uses_markers }
}

/// Idempotent install of the program's lifted `<style>` CSS at the top of
/// `container`. Delegates to the shared [`crate::emit::styles::styles_install_js`]
/// helper (the typed/TS flavor) so the synthetic emit and the production view
/// emit share one source of truth for the runtime `<style>` install.
fn styles_install_block(program: &Program) -> String {
    crate::emit::styles::styles_install_js(&program.styles, true)
}

/// Emit the SSR render module (mount-only). `controller_specifier` is the
/// import path back to the emitted synthetic controller. `mode` selects view
/// vs component lowering (used only to compute the runtime import set).
///
/// `is_view = false`: the render mounts from scratch (no SSR-adoption hydrate
/// path), and the `is_view` gates only add hydrate-buffer calls, never the
/// mount DOM — so a component-mode emitter yields the clean mount body +
/// control-flow hoists we want. This is the path ship-js SSR runs (it imports
/// the bare `mount`), so its output is held byte-identical.
pub(super) fn emit_render(
    program: &Program,
    controller_specifier: &str,
    _component_tag: Option<&str>,
) -> Result<String, CompileError> {
    if let Some(err) = unsupported_feature(&program.template) {
        return Err(err);
    }

    let walked = walk(program, false);
    let imports = render_runtime_imports(program, true);

    let mut w = Writer::new();
    w.line(HEADER);
    if !imports.is_empty() {
        w.line(&format!(
            "import {{ {} }} from \"@ship/sui-runtime\";",
            imports.join(", ")
        ));
    }
    w.line(&format!("import {{ scope }} from {};", js_string(controller_specifier)));
    w.nl();
    w.line("/** Build the view's DOM under `container`; returns a disposer. */");
    w.line("export function mount(container: HTMLElement): () => void {");
    w.enter();
    // `$scope` is the runtime-mutable scope the emitter machinery drives;
    // it inherits `scope`'s members so a machinery read of a `<data>`
    // signal resolves to the same object an author `scope.X` read does.
    // Typed `any` because the emitter adds ad-hoc props (`__v`, row binders).
    w.line("// eslint-disable-next-line @typescript-eslint/no-explicit-any");
    w.line("const $scope: any = Object.create(scope);");
    w.line("const __cleanups: Array<() => void> = [];");
    // Boundary hoists ({#if/#for/#match}, {#while-*}) are referenced by name
    // from the mount body, so they must be declared before it. They capture
    // `$scope`.
    if !walked.hoists.is_empty() {
        w.push_str(&walked.hoists);
    }
    // Inject the lifted `<style>` at the very top of `container` BEFORE
    // any element the body creates — `<style>` early in the tree
    // serializes into the SSR first-paint HTML. The same block runs in the
    // client `__mount` (see `emit_render_client`), where the dedupe makes
    // re-mounts safe.
    let styles_install = styles_install_block(program);
    if !styles_install.is_empty() {
        w.push_str(&styles_install);
    }
    w.push_str(&walked.body);
    w.line("return () => { for (const c of __cleanups) { try { c(); } catch (e) { /* dispose */ } } };");
    w.leave();
    w.line("}");
    Ok(w.into_string())
}

/// Emit the CLIENT render module: `export default component(() => …)` whose setup
/// returns `__mount` (the CSR DOM build) + `hydrate` (adopt SSR markers) —
/// the contract `packages/sui/runtime/src/mount.ts` drives. This is the
/// browser counterpart of the SSR [`emit_render`]: SAME mount body, SAME
/// boundary hoists, plus the production `hydrate(root, ctx)` buffers wired
/// against SSR'd text/element/boundary markers. The two share [`walk`]; the
/// only divergence is the export shape and the additional `@ship/sui-dom`
/// hydrate-helper imports the client contract needs.
pub(super) fn emit_render_client(
    program: &Program,
    controller_specifier: &str,
    _component_tag: Option<&str>,
) -> Result<String, CompileError> {
    if let Some(err) = unsupported_feature(&program.template) {
        return Err(err);
    }

    let walked = walk(program, true);

    // The client render is ALWAYS mount-shaped — the walk forces `is_view =
    // true` so the `hydrate` buffers populate even for a registered-component
    // target (mounted standalone). The import sets must agree with that, so
    // they are computed as the mount-form regardless of `mode`; otherwise a
    // component's hydrate body would call `hydrateText`/`hydrateOn` without
    // importing them (the component lowering leaves `dom_imports` empty).
    let mut runtime_imports = render_runtime_imports(program, true);
    if !runtime_imports.iter().any(|s| s == "component") {
        runtime_imports.push("component".to_string());
        runtime_imports.sort();
    }
    // DOM imports: the `hydrate*` helpers + `collect*` preambles the hydrate
    // body calls. Same `@ship/sui-dom` split the production view emit uses.
    let dom_imports = render_dom_imports(program, true);

    let mut w = Writer::new();
    w.line(CLIENT_HEADER);
    if !runtime_imports.is_empty() {
        w.line(&format!(
            "import {{ {} }} from \"@ship/sui-runtime\";",
            runtime_imports.join(", ")
        ));
    }
    if !dom_imports.is_empty() {
        w.line(&format!(
            "import {{ {} }} from \"@ship/sui-dom\";",
            dom_imports.join(", ")
        ));
    }
    w.line(&format!("import {{ scope }} from {};", js_string(controller_specifier)));
    w.nl();
    w.line("/** Client mount contract — `default.setup(ctx)` → `{ __mount, hydrate }`. */");
    w.line("export default component(() => {");
    w.enter();
    // eslint-disable + `any` for the same reason as the SSR render: the
    // emitter machinery adds ad-hoc props (`__v`, row binders) to `$scope`.
    w.line("// eslint-disable-next-line @typescript-eslint/no-explicit-any");
    w.line("const $scope: any = Object.create(scope);");
    if !walked.hoists.is_empty() {
        w.push_str(&walked.hoists);
    }
    // `Object.assign({}, scope, { … })` mirrors production's
    // `Object.assign({}, $scope, { … })`: the controller's scope members
    // (signals, handlers) ride on the setup return so `mount.ts` can read
    // them, alongside the `__mount`/`hydrate` contract methods.
    w.line("return Object.assign({}, scope, {");
    w.enter();
    w.line("__mount(container: HTMLElement) {");
    w.enter();
    w.line("const __cleanups: Array<() => void> = [];");
    // Inject the lifted `<style>` at the very top of `container` BEFORE
    // any element the body creates — the browser applies any in-document
    // `<style>`, regardless of location, so the same dedupe-idempotent
    // install that ships the CSS to SSR first-paint also applies it
    // here on the CSR path.
    let styles_install = styles_install_block(program);
    if !styles_install.is_empty() {
        w.push_str(&styles_install);
    }
    w.push_str(&walked.body);
    w.line("return () => { for (const c of __cleanups) { try { c(); } catch (e) { /* dispose */ } } };");
    w.leave();
    w.line("},");
    // `hydrate` only when the template binds something — matches the
    // production emit (no bindings → no hydrate property → `mount.ts` skips
    // it). The `collect*` preambles are gated on whether any text/element
    // marker was emitted, exactly like `emit_view_hydrate`.
    if !walked.hydrate_calls.is_empty() {
        w.line("hydrate(root: HTMLElement) {");
        w.enter();
        w.line("const __cleanups: Array<() => void> = [];");
        if walked.uses_text {
            w.line("const __t = collectTextOpens(root);");
        }
        if walked.uses_markers {
            w.line("const __m = collectElementMarkers(root);");
        }
        w.push_str(&walked.hydrate_calls);
        w.line("return () => { for (const c of __cleanups) { try { c(); } catch (e) { /* dispose */ } } };");
        w.leave();
        w.line("},");
    }
    w.leave();
    w.line("});");
    w.leave();
    w.line("});");
    Ok(w.into_string())
}

/// The runtime symbols the render imports from `@ship/sui-runtime`: the
/// template binders `lower` detected, minus the controller-only set.
fn render_runtime_imports(program: &Program, is_view: bool) -> Vec<String> {
    let lowered = lower::lower(program, is_view);
    let mut imports: Vec<String> = lowered
        .runtime_imports
        .iter()
        .filter(|s| !CONTROLLER_ONLY_IMPORTS.contains(s))
        .map(|s| s.to_string())
        .collect();
    for &name in &lowered.transition_builtins {
        let s = name.to_string();
        if !imports.contains(&s) {
            imports.push(s);
        }
    }
    imports.sort();
    imports
}

/// The `@ship/sui-dom` hydrate helpers the CLIENT render imports: the
/// `hydrate*` binders + `collect*` preambles `lower` detected for the
/// view's `hydrate(root, ctx)` body. Empty for the SSR render (no hydrate),
/// which is why this is client-only. Mirrors the production view emit's
/// `lowered.dom_imports` exactly.
fn render_dom_imports(program: &Program, is_view: bool) -> Vec<String> {
    let lowered = lower::lower(program, is_view);
    let mut imports: Vec<String> = lowered.dom_imports.iter().map(|s| s.to_string()).collect();
    imports.sort();
    imports
}

/// Detect template features the synthetic render cannot yet emit correctly,
/// returning a hard error rather than mis-emitting. Today that is only
/// `{#async X as v}` (`Instr::Let`): it snapshots `$scope.<name> = value`,
/// but author body reads resolve through the typed `scope.<name>` — and
/// `<name>` is not a member of the controller's `Scope`, so the two
/// diverge. Phase 2 handles `{#async}` by lifting the binding into the
/// controller's typed scope; until then it is out of scope here.
/// G5 — `{#async … as v}` lifts the `as v` binding into the typed
/// scope so the render can reference `scope.v` after the Let
/// snapshot. The render's `emit_let_block` writes `$scope.v = (value)`
/// at mount; the controller's scope declares `v: any` so the
/// type-check passes (the actual shape is the value expression's
/// return type, but we don't have that at the controller level —
/// the controller only knows the NAME; the render sees the value).
/// The slice-2 acceptance is that views using `{#async … as v}`
/// synthesize (no more unsupported-feature error) and the render
/// still drives the binding through the runtime `$scope`.
fn unsupported_feature(instrs: &[Instr]) -> Option<CompileError> {
    for instr in instrs {
        let nested: Option<&[Instr]> = match instr {
            // G5: Let (from `{#async … as v}`) is now allowed — the
            // controller declares the binding on its typed scope,
            // and the render snapshots the value into the runtime
            // `$scope` at mount.
            Instr::Let(_) => None,
            Instr::Element(el) => Some(&el.children),
            Instr::If(i) => {
                for b in &i.branches {
                    if let Some(e) = unsupported_feature(&b.body) {
                        return Some(e);
                    }
                }
                i.else_body.as_deref()
            }
            Instr::For(f) => {
                if let Some(e) = unsupported_feature(&f.body) {
                    return Some(e);
                }
                f.else_body.as_deref()
            }
            Instr::Match(m) => {
                for c in &m.cases {
                    if let Some(e) = unsupported_feature(&c.body) {
                        return Some(e);
                    }
                }
                m.default.as_deref()
            }
            Instr::WhileLoading(wl) => Some(&wl.body),
            Instr::WhileError(we) => Some(&we.body),
            _ => None,
        };
        if let Some(children) = nested
            && let Some(e) = unsupported_feature(children)
        {
            return Some(e);
        }
    }
    None
}

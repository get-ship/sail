//! `cargo run -p sui-lint --example regen_primitives [-- --check]`
//!
//! Walks the primitive packages, extracts each primitive's `<prop>`
//! declarations, and writes the canonical registry JSON consumed by
//! `sui-lint`'s `prop_registry` module.
//!
//! Modes:
//!   `regen_primitives`           — overwrite `primitives.json`.
//!   `regen_primitives --check`   — fail if regenerating would change
//!                                  the on-disk JSON. CI guard against
//!                                  drift between primitives and the
//!                                  baked registry.
//!
//! Source roots:
//!   - `packages/components/sui/primitives/src/*/*.sui`
//!   - `packages/components/ui-components/src/*/*.sui`
//!
//! Element name = filename stem (e.g. `sui-button.sui` → `sui-button`).
//! Sub-primitives in the same directory (e.g. `sui-toggle.sui` inside
//! `sui-toggle-group/`) are each registered under their own stem.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use sui_lint::prop_extract::{extract_props, PropMeta};

const HEADER_COMMENT: &str = "Generated by `cargo run -p sui-lint --example regen_primitives`. \
Do not hand-edit. Source: <prop> declarations in packages/components/sui/primitives/src/**/*.sui \
and packages/components/ui-components/src/**/*.sui. Regenerate after touching any primitive's prop API.";

const SOURCE_ROOTS: &[&str] = &[
    "packages/components/sui/primitives/src",
    "packages/components/ui-components/src",
];

const OUTPUT_PATH: &str = "crates/sui/compiler/primitives.json";

fn main() -> ExitCode {
    let check_only = std::env::args().any(|a| a == "--check");
    let repo_root = match find_repo_root() {
        Some(p) => p,
        None => {
            eprintln!(
                "regen_primitives: could not locate repository root (expected a Cargo.toml \
                 with [workspace] above cwd)"
            );
            return ExitCode::from(2);
        }
    };

    let mut primitives: BTreeMap<String, BTreeMap<String, PropEntry>> = BTreeMap::new();
    for root in SOURCE_ROOTS {
        let abs = repo_root.join(root);
        if !abs.is_dir() {
            // Missing root is not an error — repo layouts evolve.
            continue;
        }
        for sui_path in walk_sui_files(&abs) {
            let Some(stem) = sui_path.file_stem().and_then(|s| s.to_str()) else {
                continue;
            };
            // Only primitives — element names start with `sui-`.
            if !stem.starts_with("sui-") {
                continue;
            }
            let source = match std::fs::read_to_string(&sui_path) {
                Ok(s) => s,
                Err(e) => {
                    eprintln!("regen_primitives: skip {} ({})", sui_path.display(), e);
                    continue;
                }
            };
            let props = extract_props(&source);
            if props.is_empty() {
                continue;
            }
            let entry = primitives.entry(stem.to_string()).or_default();
            for p in props {
                if entry.contains_key(&p.name) {
                    eprintln!(
                        "regen_primitives: duplicate prop `{}` on `{}` (declared again at {})",
                        p.name,
                        stem,
                        sui_path.display()
                    );
                    return ExitCode::from(2);
                }
                entry.insert(p.name.clone(), PropEntry::from(p));
            }
        }
    }

    let json = render_json(&primitives);
    let out_abs = repo_root.join(OUTPUT_PATH);

    if check_only {
        match std::fs::read_to_string(&out_abs) {
            Ok(existing) if existing == json => ExitCode::SUCCESS,
            Ok(_) => {
                eprintln!(
                    "regen_primitives: {} is stale. Run \
                     `cargo run -p sui-lint --example regen_primitives` and commit.",
                    out_abs.display()
                );
                ExitCode::from(1)
            }
            Err(e) => {
                eprintln!(
                    "regen_primitives: cannot read {} ({}). Run without --check to create it.",
                    out_abs.display(),
                    e
                );
                ExitCode::from(1)
            }
        }
    } else {
        if let Err(e) = std::fs::write(&out_abs, &json) {
            eprintln!(
                "regen_primitives: write {} failed: {}",
                out_abs.display(),
                e
            );
            return ExitCode::from(2);
        }
        println!(
            "regen_primitives: wrote {} ({} primitives, {} bytes)",
            out_abs.display(),
            primitives.len(),
            json.len()
        );
        ExitCode::SUCCESS
    }
}

/// One prop's serializable shape. We hand-render JSON to keep the file
/// stable, sorted, and readable; `serde_json` would reorder optional
/// fields based on the `Serialize` derive and pull in extra deps.
struct PropEntry {
    values: Option<Vec<String>>,
    ty: Option<String>,
    default: Option<String>,
}

impl From<PropMeta> for PropEntry {
    fn from(m: PropMeta) -> Self {
        Self {
            values: m.values,
            ty: m.ty,
            default: m.default,
        }
    }
}

fn render_json(primitives: &BTreeMap<String, BTreeMap<String, PropEntry>>) -> String {
    let mut s = String::new();
    s.push_str("{\n");
    s.push_str("  \"$comment\": ");
    push_json_string(&mut s, HEADER_COMMENT);
    s.push_str(",\n");
    s.push_str("  \"primitives\": {\n");
    let total = primitives.len();
    for (idx, (element, props)) in primitives.iter().enumerate() {
        s.push_str("    ");
        push_json_string(&mut s, element);
        s.push_str(": {\n");
        let pcount = props.len();
        for (pidx, (name, rule)) in props.iter().enumerate() {
            s.push_str("      ");
            push_json_string(&mut s, name);
            s.push_str(": ");
            render_prop_entry(&mut s, rule);
            if pidx + 1 < pcount {
                s.push(',');
            }
            s.push('\n');
        }
        s.push_str("    }");
        if idx + 1 < total {
            s.push(',');
        }
        s.push('\n');
    }
    s.push_str("  }\n");
    s.push_str("}\n");
    s
}

fn render_prop_entry(s: &mut String, rule: &PropEntry) {
    let mut fields: Vec<(&str, String)> = Vec::new();
    if let Some(values) = &rule.values {
        let mut arr = String::from("[");
        for (i, v) in values.iter().enumerate() {
            if i > 0 {
                arr.push_str(", ");
            }
            push_json_string(&mut arr, v);
        }
        arr.push(']');
        fields.push(("values", arr));
    }
    if let Some(ty) = &rule.ty {
        let mut q = String::new();
        push_json_string(&mut q, ty);
        fields.push(("type", q));
    }
    if let Some(d) = &rule.default {
        let mut q = String::new();
        push_json_string(&mut q, d);
        fields.push(("default", q));
    }
    if fields.is_empty() {
        s.push_str("{}");
        return;
    }
    s.push('{');
    for (i, (key, value)) in fields.iter().enumerate() {
        if i > 0 {
            s.push_str(", ");
        } else {
            s.push(' ');
        }
        push_json_string(s, key);
        s.push_str(": ");
        s.push_str(value);
    }
    s.push_str(" }");
}

fn push_json_string(s: &mut String, raw: &str) {
    s.push('"');
    for c in raw.chars() {
        match c {
            '"' => s.push_str("\\\""),
            '\\' => s.push_str("\\\\"),
            '\n' => s.push_str("\\n"),
            '\r' => s.push_str("\\r"),
            '\t' => s.push_str("\\t"),
            c if (c as u32) < 0x20 => s.push_str(&format!("\\u{:04x}", c as u32)),
            c => s.push(c),
        }
    }
    s.push('"');
}

fn walk_sui_files(root: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let entries = match std::fs::read_dir(&dir) {
            Ok(e) => e,
            Err(_) => continue,
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                // Skip node_modules and hidden dirs as a safety net.
                if let Some(name) = path.file_name().and_then(|n| n.to_str())
                    && (name == "node_modules" || name.starts_with('.'))
                {
                    continue;
                }
                stack.push(path);
            } else if path.extension().and_then(|e| e.to_str()) == Some("sui") {
                out.push(path);
            }
        }
    }
    out.sort();
    out
}

fn find_repo_root() -> Option<PathBuf> {
    let mut p = std::env::current_dir().ok()?;
    loop {
        if p.join("Cargo.toml").is_file() {
            let txt = std::fs::read_to_string(p.join("Cargo.toml")).ok()?;
            if txt.contains("[workspace]") {
                return Some(p);
            }
        }
        if !p.pop() {
            return None;
        }
    }
}

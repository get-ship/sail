//! EXT-1 E3 end-to-end: external app depends on a component pack via
//! `node_modules` only (no `workspaces` map). A route that uses
//! `<sail-bar-chart>` must compile the pack source into the route bundle —
//! the real compile path (`bundle_target` + per-route resolver), not a
//! hand-rolled index check.
//!
//! Fixture mirrors `bun add @ship/sail-charts` into a standalone app:
//! ```text
//! app/
//!   package.json          # deps only — no workspaces
//!   routes/home/page.sail # uses <sail-bar-chart>
//!   node_modules/@ship/sail-charts/{package.json,src/...}
//! ```

use std::path::Path;

use deck_bundler::rolldown_bundle::bundle_target;
use deck_bundler::targets::{BundleLayout, BundleTarget, TargetEntry};
use deck_config::DeckConfig;

fn write(path: &Path, body: &str) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, body).unwrap();
}

/// Standalone external app + pack installed under `node_modules`. No
/// `workspaces` field anywhere — the workspace map contributes nothing.
fn external_fixture(app: &Path) {
    write(
        &app.join("package.json"),
        r#"{"name":"external-hello","dependencies":{"@ship/sail-charts":"^0.3.0"}}"#,
    );

    let pack = app.join("node_modules/@ship/sail-charts");
    write(
        &pack.join("package.json"),
        r#"{"name":"@ship/sail-charts","customElements":"dist/custom-elements.json"}"#,
    );
    write(
        &pack.join("dist/custom-elements.json"),
        r#"{"schemaVersion":"1.0.0","modules":[{"kind":"javascript-module","path":"sail-bar-chart.sail","declarations":[{"kind":"class","name":"sail-bar-chart","tagName":"sail-bar-chart","customElement":true}]}]}"#,
    );
    // Marker string proves the real pack source compiled into the route chunk.
    write(
        &pack.join("src/sail-bar-chart/sail-bar-chart.sail"),
        "<div>sail-bar-chart-marker</div>\n",
    );

    write(
        &app.join("routes/home/page.sail"),
        "<div><sail-bar-chart></sail-bar-chart></div>\n",
    );
}

fn home_route(app: &Path) -> BundleTarget {
    BundleTarget {
        name: "routes/home/route".into(),
        entry: TargetEntry::Real(app.join("routes/home/page.sail")),
        externals: vec![],
        out_file: "routes/home/route.js".into(),
        lazy: false,
    }
}

/// Named acceptance: external pack via node_modules, no workspace map, real
/// compile path — route bundle carries the pack component's source.
#[tokio::test(flavor = "multi_thread")]
async fn external_pack_via_node_modules_compiles_into_route_bundle() {
    let src = tempfile::tempdir().unwrap();
    let app = src.path();
    external_fixture(app);

    // Pre-condition: discovery is node_modules-only (no workspaces globs).
    let pkgs = deck_bundler::catalog::discover_workspace_packages(app).expect("discover");
    assert_eq!(
        pkgs.len(),
        1,
        "external app must discover exactly the node_modules pack"
    );
    assert_eq!(pkgs[0].name, "@ship/sail-charts");
    assert!(
        pkgs[0].root.ends_with("node_modules/@ship/sail-charts"),
        "pack root under node_modules; got {:?}",
        pkgs[0].root
    );

    // components.gen includes the pack (B2 catalog emission).
    let n = deck_bundler::cem::generate_components_gen(app, app).expect("components.gen");
    assert_eq!(n, 1, "components.gen must include the node_modules pack");
    let catalog = std::fs::read_to_string(app.join("components.gen.ts")).unwrap();
    assert!(
        catalog.contains("sail-bar-chart") && catalog.contains("@ship/sail-charts"),
        "components.gen must list tag + package; got:\n{catalog}"
    );

    // Real compile path: per-route resolver pulls pack source into the chunk.
    let out = tempfile::tempdir().unwrap();
    let layout = BundleLayout::with_config(app.to_path_buf(), None, DeckConfig::defaults())
        .with_out_root(out.path().to_path_buf());
    let staging = out.path().join("_staging");
    std::fs::create_dir_all(&staging).unwrap();
    bundle_target(&layout, &home_route(app), &staging, false)
        .await
        .expect("route must bundle with external pack");

    let js = std::fs::read_to_string(out.path().join(".deck/routes/home/route.js"))
        .expect("route.js written");
    assert!(
        js.contains("sail-bar-chart-marker"),
        "route bundle must carry the node_modules pack component; got:\n{js}"
    );
}

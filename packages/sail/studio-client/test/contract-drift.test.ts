/**
 * Contract-drift guards (SPEC-STUDIO-CONTRACT-1):
 * (a) committed generated client matches METHOD_CONTRACTS-derived export names
 *     (freshness is also asserted in sail-ops Rust via assert_no_drift)
 * (b) every sail[A-Z]* call site in apps/studio/src exists in the generated client
 * (c) every core generated sail* method is consumed or explicitly allow-listed
 */
import { describe, expect, it } from 'vitest'
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as client from '../src/index'

const pkgRoot = join(fileURLToPath(import.meta.url), '..', '..')
const repoRoot = join(pkgRoot, '..', '..', '..')
const studioSrc = join(repoRoot, 'apps/studio/src')
const generatedPath = join(pkgRoot, 'src/generated/client.ts')

/** Core methods intentionally unconsumed by studio UI today (queue / deferred). */
const CORE_ALLOWLIST = new Set([
  // Progressive disclosure / agent CLI; Config surface stub does not call it yet.
  'sailAuthoringSurface',
  // Editor hover/complete are imported by ops-adapter wiring path but CodeMirror
  // consumption is still partial — keep listed as unconsumed core until editor binds.
  'sailAuthoringHover',
  'sailAuthoringComplete',
  // Policy registry — Config writes not wired (CONTRACT-DIFF §4.2/§4.1).
  'sailAuthoringPolicy',
  // Generic multi-topic inspect; studio uses Model/Tree/State/TokenUsage.
  'sailInspectInspect',
  // Dev server lifecycle — Config shows URL only (CONTRACT-DIFF §4.2).
  'sailDevServerStart',
  'sailDevServerStatus',
  'sailDevServerStop',
  // Task update field-patch; UI uses comment/reply/reanchor/commit paths.
  'sailTaskUpdate',
])

const SKIP_DIRS = new Set([
  'node_modules',
  'dist',
  '.sail-out',
  'target',
])

function* walkTs(dir: string): Generator<string> {
  let entries: string[]
  try {
    entries = readdirSync(dir)
  } catch {
    return
  }
  for (const e of entries) {
    if (SKIP_DIRS.has(e)) continue
    const p = join(dir, e)
    let st
    try {
      st = statSync(p)
    } catch {
      continue
    }
    if (st.isDirectory()) yield* walkTs(p)
    else if (/\.(ts|tsx|sail)$/.test(e)) yield p
  }
}

function generatedSailFns(): Set<string> {
  const names = new Set<string>()
  for (const [k, v] of Object.entries(client)) {
    if (typeof v === 'function' && /^sail[A-Z]/.test(k)) names.add(k)
  }
  return names
}

function consumedSailFns(): Set<string> {
  // Property access: client.sailFoo / ops.sailFoo
  const propRe = /\b(?:client|ops|opsClient)\.sail([A-Z][A-Za-z0-9]*)\b/g
  // Imports from studio-client
  const importRe = /\bsail([A-Z][A-Za-z0-9]*)\b/g
  // Type Pick keys as string literals in surface types
  const pickKeyRe = /'\s*sail([A-Z][A-Za-z0-9]*)\s*'/g
  // createOpsClient / CLI adapter object keys
  const keyRe = /\bsail([A-Z][A-Za-z0-9]*)\s*[:(]/g

  const found = new Set<string>()
  for (const file of walkTs(studioSrc)) {
    const text = readFileSync(file, 'utf8')
    // Skip pure domain type files that only re-export Pick keys? No — include them.
    for (const re of [propRe, importRe, pickKeyRe, keyRe]) {
      re.lastIndex = 0
      let m: RegExpExecArray | null
      while ((m = re.exec(text))) {
        found.add(`sail${m[1]}`)
      }
    }
  }
  return found
}

describe('studio contract drift', () => {
  it('(a) generated client is present and exports sail* unaries', () => {
    const body = readFileSync(generatedPath, 'utf8')
    expect(body).toMatch(/GENERATED by `sail op gen`/)
    const fns = generatedSailFns()
    expect(fns.size).toBeGreaterThan(20)
    expect(fns.has('sailAuthoringEdit')).toBe(true)
    expect(fns.has('sailThemeFontSearch')).toBe(true)
    // writeSource is a field on EditArgs, not a top-level method.
    expect(body).toMatch(/writeSource\?:/)
    expect(body).toMatch(/category\?:/)
    expect(body).toMatch(/limit\?:/)
  })

  it('(b) every sail* call in apps/studio/src exists on the generated client', () => {
    const gen = generatedSailFns()
    const consumed = consumedSailFns()
    // Local helpers — not Connect methods.
    const local = new Set(['sailStreamTokenizer']) // cm tokenizer, not ops
    const unknown: string[] = []
    for (const name of consumed) {
      if (local.has(name)) continue
      if (!gen.has(name) && !name.startsWith('sailStream')) {
        // Filter false positives from non-ops identifiers that match the regex.
        if (
          name === 'sailPath' ||
          name === 'sailNodes' ||
          name === 'sailMode' ||
          name.startsWith('sailStudio') ||
          name.startsWith('sailCmd') ||
          name.startsWith('sailCode')
        ) {
          continue
        }
        if (!gen.has(name)) unknown.push(name)
      }
    }
    expect(unknown, `unknown ops calls: ${unknown.join(', ')}`).toEqual([])
  })

  it('(c) every core sail* method is consumed or allow-listed', () => {
    const gen = generatedSailFns()
    const consumed = consumedSailFns()
    const dead: string[] = []
    for (const name of gen) {
      if (CORE_ALLOWLIST.has(name)) continue
      if (!consumed.has(name)) dead.push(name)
    }
    expect(
      dead,
      `unconsumed core methods (add consumer or CORE_ALLOWLIST): ${dead.join(', ')}`,
    ).toEqual([])
  })

  it('allow-list entries still exist on the generated client', () => {
    const gen = generatedSailFns()
    for (const name of CORE_ALLOWLIST) {
      expect(gen.has(name), `stale allow-list entry ${name}`).toBe(true)
    }
  })

  it('no hand-written OpsClient type bodies remain in apps/studio/src', () => {
    // Guard: client types must derive via Pick/StudioOpsMethods, not inline shapes.
    for (const file of walkTs(studioSrc)) {
      const text = readFileSync(file, 'utf8')
      if (!/OpsClient\s*=/.test(text)) continue
      const rel = relative(repoRoot, file)
      expect(
        text,
        `${rel}: OpsClient must Pick from StudioOpsMethods`,
      ).toMatch(/StudioOpsMethods/)
      // Forbid the old hand-written pattern of method: (args: { … }) => Promise<{
      expect(
        text,
        `${rel}: hand-written client method bodies forbidden`,
      ).not.toMatch(
        /OpsClient\s*=\s*\{[\s\S]*sail[A-Z][A-Za-z]+\s*[?:]?\s*:\s*\(\s*args\s*:/,
      )
    }
  })
})
